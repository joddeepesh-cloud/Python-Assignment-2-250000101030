# Solution
num1 = 17
num2 = 5

floor_div = num1 // num2
modulus = num1 % num2

print(f"Given numbers: {num1} and {num2}")
print(f"Floor Division ({num1} // {num2}) = {floor_div} (discards the fractional part)")
print(f"Modulus        ({num1} % {num2})  = {modulus} (gives the remainder)")
