# Solution
# 12 in binary: 0000 1100
# 25 in binary: 0001 1001
a = 12
b = 25

print(f"a = {a} (bin: {bin(a)}), b = {b} (bin: {bin(b)})")
print(f"Bitwise AND (a & b): {a & b} (bin: {bin(a & b)})")
print(f"Bitwise OR  (a | b): {a | b} (bin: {bin(a | b)})")
print(f"Bitwise XOR (a ^ b): {a ^ b} (bin: {bin(a ^ b)})")
