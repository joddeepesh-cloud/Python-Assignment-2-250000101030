# Solution
a = 15
b = 4

float_div = a / b
floor_div = a // b

print(f"a = {a}, b = {b}")
print(f"a / b  (Standard Division) = {float_div} (always produces float)")
print(f"a // b (Floor Division)    = {floor_div} (rounds down to nearest integer)")
